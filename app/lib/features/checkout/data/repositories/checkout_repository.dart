import 'package:supabase_flutter/supabase_flutter.dart';
import '../../../../core/constants/app_constants.dart';
import '../../../../core/services/supabase_service.dart';
import '../../../cart/data/models/cart_item_model.dart';
import '../models/checkout_result_model.dart';

/// Repository coordinating checkout preparation and order creation via Supabase Edge Functions.
class CheckoutRepository {
  CheckoutRepository({SupabaseClient? client}) : _client = client;

  final SupabaseClient? _client;

  SupabaseClient get _effectiveClient {
    if (_client != null) return _client;
    if (AppConstants.isSupabaseConfigured) {
      return Supabase.instance.client;
    }
    throw StateError('Supabase is not configured.');
  }

  bool get isReady => _client != null || AppConstants.isSupabaseConfigured;

  String? get currentUserId =>
      _client?.auth.currentUser?.id ?? SupabaseService.instance.currentUserId;

  /// Synchronizes local cart items to the database `carts` and `cart_items` tables.
  ///
  /// This ensures the server-side `initiate-checkout` function has access to the
  /// customer's exact items, while enforcing that authoritative prices and inventory
  /// checks are performed strictly on the backend.
  Future<bool> syncCartToSupabase(List<CartItem> items) async {
    if (!isReady) return false;
    final userId = currentUserId;
    if (userId == null) return false;

    try {
      // 1. Ensure user's cart row exists
      final cartResponse = await _effectiveClient
          .from('carts')
          .select('id')
          .eq('customer_id', userId)
          .maybeSingle();

      String cartId;
      if (cartResponse == null) {
        final newCart = await _effectiveClient
            .from('carts')
            .insert({'customer_id': userId})
            .select('id')
            .single();
        cartId = newCart['id'] as String;
      } else {
        cartId = cartResponse['id'] as String;
      }

      // 2. Clear existing cart items
      await _effectiveClient
          .from('cart_items')
          .delete()
          .eq('cart_id', cartId);

      // 3. Insert latest items
      if (items.isNotEmpty) {
        final payload = items.map((item) {
          return {
            'cart_id': cartId,
            'product_id': item.product.id,
            'vendor_id': item.product.vendorId,
            'quantity': item.quantity,
            'unit_price': item.product.price,
          };
        }).toList();

        await _effectiveClient.from('cart_items').insert(payload);
      }

      return true;
    } catch (_) {
      return false;
    }
  }

  /// Calls the `initiate-checkout` Edge Function to validate items, calculate
  /// authoritative totals, and create pending multi-vendor orders.
  ///
  /// [idempotencyKey] — a UUID v4 generated by the caller before the first
  /// attempt.  Pass the same key on retries (e.g. after a network timeout) so
  /// the server returns the original order result instead of creating a new one.
  /// If omitted, the server generates a fresh UUID (no replay protection for that
  /// specific call).
  Future<CheckoutResult> initiateCheckout({
    required String shippingAddressId,
    String? notes,
    String? idempotencyKey,
  }) async {
    if (!isReady) {
      return CheckoutResult.failure('Backend database is not configured.');
    }
    final userId = currentUserId;
    if (userId == null) {
      return CheckoutResult.failure('Please sign in to complete checkout.');
    }

    try {
      final body = <String, dynamic>{
        'shipping_address_id': shippingAddressId,
        if (notes != null && notes.trim().isNotEmpty) 'notes': notes.trim(),
        if (idempotencyKey != null) 'idempotency_key': idempotencyKey,
      };

      final response = await _effectiveClient.functions.invoke(
        'initiate-checkout',
        body: body,
      );

      final data = response.data;
      if (response.status == 200 && data is Map<String, dynamic>) {
        return CheckoutResult.fromMap(data);
      }

      if (data is Map<String, dynamic> && data['error'] != null) {
        return CheckoutResult.failure(data['error'].toString());
      }

      return CheckoutResult.failure(
        'Server returned error status (${response.status}).',
      );
    } on FunctionException catch (e) {
      final details = e.details;
      if (details is Map<String, dynamic> && details['error'] != null) {
        return CheckoutResult.failure(details['error'].toString());
      }
      return CheckoutResult.failure(e.reasonPhrase ?? e.toString());
    } catch (e) {
      return CheckoutResult.failure('Failed to initiate checkout: $e');
    }
  }
}
